#!/usr/bin/env python3
"""Generate src/prayer/PrayerHijriTable.h (Umm al-Qura month lengths).

The prayer app shows the Hijri date beside the Gregorian one. Computing it
from a tabular ("Kuwaiti") arithmetic calendar is cheap but drifts a day from
the Umm al-Qura calendar that Saudi Arabia -- and every Hijri date a user is
likely to compare against -- actually uses, so ship the real month lengths
instead.

One uint16 per Hijri year carries twelve bits, bit i set when month i+1 has
30 days (29 otherwise): about 200 bytes for a century. The Gregorian day
ordinal of the first year's first day anchors the whole table, and every
later date follows by accumulation.

Source: the `hijridate` package (formerly hijri-converter), which embeds the
Umm al-Qura data for 1343-1500 AH.

  pip install hijridate
  python scripts/gen_prayer_hijri.py --first 1400 --last 1500
"""

import argparse
import datetime
import sys

try:
    from hijridate import Hijri
except ImportError:  # the package was called hijri-converter before 2.3
    try:
        from hijri_converter import Hijri
    except ImportError:
        sys.exit("needs hijridate: pip install hijridate")

EPOCH = datetime.date(1970, 1, 1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--first", type=int, default=1400)
    ap.add_argument("--last", type=int, default=1499)  # the data ends at 1500 AH, and year N needs 1 Muharram N+1
    ap.add_argument("--out", default="src/prayer/PrayerHijriTable.h")
    args = ap.parse_args()

    masks = []
    for year in range(args.first, args.last + 1):
        mask = 0
        for month in range(1, 13):
            start = Hijri(year, month, 1).to_gregorian()
            nxt = Hijri(year + 1, 1, 1) if month == 12 else Hijri(year, month + 1, 1)
            length = (nxt.to_gregorian().datetuple() and
                      (datetime.date(*nxt.to_gregorian().datetuple()) -
                       datetime.date(*start.datetuple())).days)
            if length not in (29, 30):
                sys.exit("unexpected month length %d for %d-%d" % (length, year, month))
            if length == 30:
                mask |= 1 << (month - 1)
        masks.append(mask)

    first_day = datetime.date(*Hijri(args.first, 1, 1).to_gregorian().datetuple())
    first_ordinal = (first_day - EPOCH).days

    lines = [
        "// Generated by scripts/gen_prayer_hijri.py -- do not edit.",
        "// Umm al-Qura month lengths for %d-%d AH (%s to the end of that span)."
        % (args.first, args.last, first_day.isoformat()),
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace PrayerHijriData {",
        "",
        "// Day ordinal (days since 1970-01-01) of 1 Muharram %d AH." % args.first,
        "static constexpr int32_t FIRST_DAY_ORDINAL = %d;" % first_ordinal,
        "static constexpr uint16_t FIRST_YEAR = %d;" % args.first,
        "static constexpr uint16_t YEAR_COUNT = %d;" % len(masks),
        "",
        "// Bit i set: month i+1 of that year has 30 days, otherwise 29.",
        "static constexpr uint16_t MONTH_LENGTHS[] = {",
    ]
    for i in range(0, len(masks), 8):
        lines.append("    " + " ".join("0x%04X," % m for m in masks[i:i + 8]))
    lines += ["};", "", "}  // namespace PrayerHijriData", ""]

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %s: %d years from %d AH (anchor ordinal %d = %s)"
          % (args.out, len(masks), args.first, first_ordinal, first_day.isoformat()))


if __name__ == "__main__":
    main()
